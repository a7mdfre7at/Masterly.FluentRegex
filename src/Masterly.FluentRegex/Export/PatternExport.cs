#nullable enable
using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Masterly.FluentRegex.Export;

namespace Masterly.FluentRegex;

/// <summary>
/// Generates source files that share .NET patterns with other languages, so client and server
/// validate with the same rules.
/// </summary>
public static class PatternExport
{
    private const string DefaultHeader = "Generated by Masterly.FluentRegex. Do not edit by hand.";
    private const string LineComment = "// ";
    private const string NewLine = "\n";
    private const string PatternsParameter = "patterns";

    /// <summary>
    /// Generates a TypeScript (and JavaScript) module with one exported regex constant per pattern,
    /// in ordinal order of the names, each documented with its .NET source and any warnings.
    /// </summary>
    /// <param name="patterns">The patterns keyed by constant name, which must be a valid identifier.</param>
    /// <param name="header">
    /// Comment lines at the top of the file; null for a "generated" notice, empty for none.
    /// </param>
    /// <returns>The module source, for example <c>export const sku = /^[A-Z]{3}-\p{Nd}{4}(?=\n?$)/u;</c>.</returns>
    /// <exception cref="ArgumentNullException"><paramref name="patterns"/> is null.</exception>
    /// <exception cref="ArgumentException">A name is not a valid identifier, or a pattern is null.</exception>
    /// <exception cref="NotSupportedException">A pattern cannot be expressed in JavaScript; the message names it.</exception>
    public static string ToTypeScript(IReadOnlyDictionary<string, Pattern> patterns, string? header = null)
    {
        if (patterns == null)
        {
            throw new ArgumentNullException(nameof(patterns));
        }

        StringBuilder sb = new StringBuilder();
        AppendHeader(sb, header ?? DefaultHeader);
        foreach (KeyValuePair<string, Pattern> entry in patterns.OrderBy(pair => pair.Key, StringComparer.Ordinal))
        {
            AppendConstant(sb, entry.Key, entry.Value);
        }

        return sb.ToString();
    }

    private static void AppendHeader(StringBuilder sb, string header)
    {
        if (header.Length == 0)
        {
            return;
        }

        foreach (string line in header.Replace("\r\n", NewLine).Split('\n'))
        {
            sb.Append(LineComment).Append(line).Append(NewLine);
        }

        sb.Append(NewLine);
    }

    private static void AppendConstant(StringBuilder sb, string name, Pattern pattern)
    {
        if (!EcmaIdentifier.IsBindingName(name))
        {
            throw new ArgumentException($"'{name}' is not a valid TypeScript identifier.", PatternsParameter);
        }

        if (pattern == null)
        {
            throw new ArgumentException($"The pattern for '{name}' is null.", PatternsParameter);
        }

        FlavorConversion conversion = Convert(name, pattern);
        sb.Append("/**").Append(NewLine);
        sb.Append(" * .NET: ").Append(CommentText(pattern.ToString())).Append(NewLine);
        foreach (string warning in conversion.Warnings)
        {
            sb.Append(" * Warning: ").Append(CommentText(warning)).Append(NewLine);
        }

        sb.Append(" */").Append(NewLine);
        sb.Append($"export const {name} = {conversion.ToLiteral()};").Append(NewLine);
    }

    private static FlavorConversion Convert(string name, Pattern pattern)
    {
        try
        {
            return pattern.ToFlavor(RegexFlavor.JavaScript);
        }
        catch (NotSupportedException ex)
        {
            throw new NotSupportedException($"The pattern '{name}' cannot be exported: {ex.Message}", ex);
        }
    }

    /// <summary>Keeps a value on one comment line and prevents it from closing the comment.</summary>
    private static string CommentText(string text) =>
        text.Replace("*/", @"*\/").Replace("\r", @"\r").Replace("\n", @"\n");
}
