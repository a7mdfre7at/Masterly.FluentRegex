using System.Collections.Generic;
using System.Collections.Immutable;
using System.Composition;
using System.Globalization;
using System.Linq;
using System.Threading;
using System.Threading.Tasks;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CodeActions;
using Microsoft.CodeAnalysis.CodeFixes;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Formatting;

namespace Masterly.FluentRegex.CodeFixes
{
    /// <summary>
    /// Adds a <c>[GeneratedRegex]</c> partial method next to a constant fluent pattern. The pattern
    /// text was evaluated by the analyzer, so the .NET regex source generator can take over from here.
    /// </summary>
    [ExportCodeFixProvider(LanguageNames.CSharp, Name = nameof(GeneratedRegexCodeFix)), Shared]
    public sealed class GeneratedRegexCodeFix : CodeFixProvider
    {
        // Must match the analyzer's diagnostic id and property names.
        public const string DiagnosticId = "FRX007";
        private const string PatternProperty = "Pattern";
        private const string OptionsProperty = "Options";
        private const string TimeoutProperty = "TimeoutMilliseconds";

        public override ImmutableArray<string> FixableDiagnosticIds { get; } = ImmutableArray.Create(DiagnosticId);

        public override FixAllProvider GetFixAllProvider() => WellKnownFixAllProviders.BatchFixer;

        public override async Task RegisterCodeFixesAsync(CodeFixContext context)
        {
            SyntaxNode root = await context.Document.GetSyntaxRootAsync(context.CancellationToken).ConfigureAwait(false);
            if (root == null) return;

            foreach (Diagnostic diagnostic in context.Diagnostics)
            {
                if (!diagnostic.Properties.TryGetValue(PatternProperty, out string pattern) || pattern == null) continue;
                SyntaxToken identifier = root.FindToken(diagnostic.Location.SourceSpan.Start);
                MemberDeclarationSyntax member = identifier.Parent?.AncestorsAndSelf().OfType<MemberDeclarationSyntax>()
                    .FirstOrDefault(m => m is FieldDeclarationSyntax || m is PropertyDeclarationSyntax);
                if (member == null) continue;

                string name = identifier.ValueText + "Regex";
                context.RegisterCodeFix(
                    CodeAction.Create(
                        "Add [GeneratedRegex] method '" + name + "()'",
                        ct => AddMethodAsync(context.Document, member, identifier.ValueText, name, diagnostic.Properties, ct),
                        equivalenceKey: DiagnosticId),
                    diagnostic);
            }
        }

        private static async Task<Document> AddMethodAsync(Document document, MemberDeclarationSyntax member, string memberName, string baseName,
            ImmutableDictionary<string, string> properties, CancellationToken cancellationToken)
        {
            SyntaxNode root = await document.GetSyntaxRootAsync(cancellationToken).ConfigureAwait(false);
            var type = (TypeDeclarationSyntax)member.Parent;

            var existing = new HashSet<string>(type.Members.OfType<MethodDeclarationSyntax>().Select(m => m.Identifier.ValueText));
            string name = baseName;
            for (int i = 2; existing.Contains(name); i++) name = baseName + i.ToString(CultureInfo.InvariantCulture);

            string arguments = Literal(properties[PatternProperty]);
            int options = int.Parse(properties[OptionsProperty], CultureInfo.InvariantCulture) & ~8; // Compiled is implied by the generator
            properties.TryGetValue(TimeoutProperty, out string timeout);
            bool hasTimeout = !string.IsNullOrEmpty(timeout);
            if (options != 0 || hasTimeout) arguments += ", " + OptionsCode(options);
            if (hasTimeout) arguments += ", " + timeout;

            string code =
                "/// <summary>Generated by the .NET regex source generator from <see cref=\"" + memberName + "\"/>.</summary>\n" +
                "[global::System.Text.RegularExpressions.GeneratedRegex(" + arguments + ")]\n" +
                "private static partial global::System.Text.RegularExpressions.Regex " + name + "();\n";

            MemberDeclarationSyntax method = SyntaxFactory.ParseMemberDeclaration(code)
                .WithAdditionalAnnotations(Formatter.Annotation);

            SyntaxNode newRoot = root.InsertNodesAfter(member, new[] { method });
            return document.WithSyntaxRoot(newRoot);
        }

        private static string Literal(string value)
        {
            foreach (char c in value)
            {
                if (char.IsControl(c)) return SymbolDisplay.FormatLiteral(value, quote: true);
            }
            return "@\"" + value.Replace("\"", "\"\"") + "\"";
        }

        private static string OptionsCode(int options)
        {
            if (options == 0) return "global::System.Text.RegularExpressions.RegexOptions.None";
            string[] names = { "IgnoreCase", "Multiline", "ExplicitCapture", "Compiled", "Singleline", "IgnorePatternWhitespace", "RightToLeft", null, "ECMAScript", "CultureInvariant", "NonBacktracking" };
            var parts = new List<string>();
            for (int bit = 0; bit < names.Length; bit++)
            {
                if ((options & (1 << bit)) != 0 && names[bit] != null)
                    parts.Add("global::System.Text.RegularExpressions.RegexOptions." + names[bit]);
            }
            return string.Join(" | ", parts);
        }
    }
}
