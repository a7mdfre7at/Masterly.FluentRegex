using Masterly.FluentRegex.Cli.Tests.Infrastructure;

namespace Masterly.FluentRegex.Cli.Tests;

[Collection(CliCollection.Name)]
public sealed class ExportCommandTests : CliTestBase
{
    [Fact]
    public void Export_DefaultTarget_PrintsJavaScriptLiteral()
    {
        CliResult result = Run("export", @"\d+");

        result.ExitCode.ShouldBe(Ok);
        result.Output.ShouldBe(@"/\p{Nd}+/u" + Environment.NewLine);
        result.Error.ShouldBeEmpty();
    }

    [Theory]
    [InlineData("js")]
    [InlineData("javascript")]
    [InlineData("JS")]
    public void Export_JavaScriptTarget_PrintsLiteral(string target)
    {
        CliResult result = Run("export", "a", "--to", target);

        result.ExitCode.ShouldBe(Ok);
        result.Output.ShouldBe("/a/u" + Environment.NewLine);
    }

    [Theory]
    [InlineData("json-schema")]
    [InlineData("jsonschema")]
    public void Export_JsonSchemaTarget_PrintsBarePattern(string target)
    {
        CliResult result = Run("export", @"(?<y>\d+)", "--to", target);

        result.ExitCode.ShouldBe(Ok);
        result.Output.ShouldBe(@"(?<y>\p{Nd}+)" + Environment.NewLine);
    }

    [Fact]
    public void Export_TypeScriptWithName_PrintsNamedConstant()
    {
        CliResult result = Run("export", @"\d+", "--to", "typescript", "--name", "digits");

        result.ExitCode.ShouldBe(Ok);
        result.Output.ShouldContain("// Generated by Masterly.FluentRegex. Do not edit by hand.");
        result.Output.ShouldContain(@" * .NET: \d+");
        result.Output.ShouldContain(@"export const digits = /\p{Nd}+/u;");
    }

    [Fact]
    public void Export_TypeScriptWithoutName_UsesPatternAsTheConstantName()
    {
        CliResult result = Run("export", "a", "--to", "TypeScript");

        result.ExitCode.ShouldBe(Ok);
        result.Output.ShouldContain("export const pattern = /a/u;");
    }

    [Fact]
    public void Export_ConstructWithDifferentSemantics_PrintsWarningsAfterTheResult()
    {
        CliResult result = Run("export", "a.b");

        result.ExitCode.ShouldBe(Ok);
        result.OutputLines[0].ShouldBe(@"/a[^\n]b/u");
        result.OutputLines[1].ShouldStartWith("warning: Supplementary characters such as emoji");
    }

    [Fact]
    public void Export_UnknownTarget_ReturnsUsageError()
    {
        CliResult result = Run("export", "a", "--to", "python");

        result.ExitCode.ShouldBe(UsageError);
        result.Output.ShouldBeEmpty();
        result.Error.ShouldBe(
            "error: Unknown --to 'python'. Use js, json-schema, typescript, postgresql, mysql, mariadb, sqlserver, sqlite or like." +
            Environment.NewLine);
    }

    [Theory]
    [InlineData("postgresql", @"'\A[0-9]+(?=\n?\Z)'")]
    [InlineData("pg", @"'\A[0-9]+(?=\n?\Z)'")]
    [InlineData("mysql", @"'(?-i)\\A[0-9]+(?=\\n?\\z)'")]
    [InlineData("mariadb", @"'(?-i)\\A[0-9]+(?=\\n?\\z)'")]
    [InlineData("sqlserver", @"N'\A[0-9]+\n?\z'")]
    [InlineData("sqlite", "'^[0-9]+$'")]
    public void Export_SqlTarget_PrintsTheQuotedDialectLiteral(string target, string expected)
    {
        CliResult result = Run("export", "^[0-9]+$", "--to", target);

        result.ExitCode.ShouldBe(Ok);
        result.Output.ShouldBe(expected + Environment.NewLine);
    }

    [Fact]
    public void Export_SqlTargetWithColumn_PrintsTheWhereCondition()
    {
        CliResult result = Run("export", "^[0-9]+$", "--to", "postgresql", "--column", "\"Number\"");

        result.ExitCode.ShouldBe(Ok);
        result.Output.ShouldBe(@"""Number"" ~ '\A[0-9]+(?=\n?\Z)'" + Environment.NewLine);
    }

    [Fact]
    public void Export_SqlTargetWithUnsupportedConstruct_ReturnsUsageErrorNamingIt()
    {
        CliResult result = Run("export", "(?<=a)b", "--to", "sqlserver");

        result.ExitCode.ShouldBe(UsageError);
        result.Error.ShouldContain("lookaround");
    }

    [Fact]
    public void Export_LikeProvenExact_PrintsTheConditionAndTheExactVerdict()
    {
        CliResult result = Run("export", @"^INV-[0-9]{4}\z", "--to", "like", "--dialect", "sqlserver", "--column", "[Number]");

        result.ExitCode.ShouldBe(Ok);
        result.OutputLines[0].ShouldBe("[Number] LIKE 'INV-[0-9][0-9][0-9][0-9]'");
        result.OutputLines[1].ShouldStartWith("exact:");
    }

    [Fact]
    public void Export_LikeEndingInDollar_PrintsASupersetWithItsReason()
    {
        CliResult result = Run("export", "^INV-[0-9]{4}$", "--to", "like", "--dialect", "sqlserver");

        result.ExitCode.ShouldBe(Ok);
        result.OutputLines[0].ShouldBe("INV-[0-9][0-9][0-9][0-9]%");
        result.OutputLines[1].ShouldStartWith("superset:");
        result.Output.ShouldContain(@"end the pattern with '\z'");
    }

    [Fact]
    public void Export_LikeCaseInsensitiveCollation_IsNeverExactForCasedLetters()
    {
        CliResult result = Run("export", @"^INV\z", "--to", "like", "--dialect", "sqlserver", "--case-insensitive");

        result.ExitCode.ShouldBe(Ok);
        result.OutputLines[1].ShouldStartWith("superset:");
    }

    [Fact]
    public void Export_LikeUnknownDialect_ReturnsUsageError()
    {
        CliResult result = Run("export", "a", "--to", "like", "--dialect", "oracle");

        result.ExitCode.ShouldBe(UsageError);
        result.Error.ShouldContain("Unknown --dialect 'oracle'");
    }

    [Fact]
    public void Export_UntranslatableConstruct_ReturnsUsageError()
    {
        CliResult result = Run("export", "(?(a)b|c)");

        result.ExitCode.ShouldBe(UsageError);
        result.Error.ShouldContain("conditional '(?(a)...)' at position 0");
    }
}
